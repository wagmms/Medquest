def main():
    conn = sqlite3.connect(DB)
    cur = conn.cursor()
    # validação: todo destino precisa ser canônico da sua área
    problems = []
    for area, m in MAPPING.items():
        canon = set(CANONICAL[area])
        for src, dst in m.items():
            if dst not in canon:
                problems.append(f"{area}: destino inválido '{dst}' (de '{src}')")
    if problems:
        print("ABORTADO — destinos inválidos:")
        print("\n".join(problems))
        return

    total = 0
    for area, m in MAPPING.items():
        for src, dst in m.items():
            cur.execute("UPDATE questions SET subtema=? WHERE area=? AND subtema=?", (dst, area, src))
            total += cur.rowcount
    conn.commit()
    print(f"Reclassificação manual aplicada: {total} questões atualizadas.")

    print("\nSubtemas distintos por área agora:")
    for area, in cur.execute("SELECT DISTINCT area FROM questions WHERE area!='' ORDER BY area"):
        n = cur.execute("SELECT COUNT(DISTINCT subtema) FROM questions WHERE area=? AND subtema!=''", (area,)).fetchone()[0]
        canon = set(CANONICAL.get(area, []))
        rest = cur.execute(f"SELECT COUNT(*) FROM questions WHERE area=? AND missing_alts=0 AND subtema!='' AND subtema NOT IN ({','.join('?'*len(canon))})", (area, *canon)).fetchone()[0]
        print(f"  {area}: {n} subtemas | ainda não-canônicos: {rest}")
    conn.close()


if __name__ == "__main__":
    main()
